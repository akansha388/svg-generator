def render_icon(
    icon_name: str,
    x: float,
    y: float,
    size: int = 24,
    color: str = "#FFFFFF",
    stroke_width: float = 2.0,
    background_circle: bool = False,
    bg_color: str = "rgba(255,255,255,0.1)",
    bg_radius: float = 18.0,
) -> str:
    """
    Renders an SVG group containing the specified icon centered at (x, y) or positioned at (x, y).
    """
    path_data = ICONS.get(icon_name, ICONS.get("sparkles", ""))
    
    parts = []
    if background_circle:
        cx = x + size / 2
        cy = y + size / 2
        parts.append(
            f'<circle cx="{cx:.1f}" cy="{cy:.1f}" r="{bg_radius:.1f}" fill="{bg_color}" />'
        )
    
    scale = size / 24.0
    group_attrs = (
        f'transform="translate({x:.1f}, {y:.1f}) scale({scale:.3f})" '
        f'stroke="{color}" fill="none" stroke-width="{stroke_width}" '
        f'stroke-linecap="round" stroke-linejoin="round"'
    )
    
    parts.append(f'<g {group_attrs}>{path_data}</g>')
    return "".join(parts)


def get_category_default_icon(category: str) -> str:
    """Map a topic category to a suitable default icon."""
    cat_lower = category.lower()
    if "tech" in cat_lower or "ai" in cat_lower:
        return "cpu"
    elif "cyber" in cat_lower or "security" in cat_lower:
        return "shield_check"
    elif "business" in cat_lower or "startup" in cat_lower:
        return "rocket"
    elif "finance" in cat_lower:
        return "chart_bar"
    elif "health" in cat_lower:
        return "heart_pulse"
    elif "edu" in cat_lower:
        return "graduation_cap"
    elif "sustain" in cat_lower or "eco" in cat_lower:
        return "leaf"
    elif "market" in cat_lower:
        return "mega_phone"
    elif "commerce" in cat_lower:
        return "wallet"
    elif "estate" in cat_lower:
        return "building"
    elif "productiv" in cat_lower:
        return "zap"
    elif "social" in cat_lower:
        return "share"
    elif "announce" in cat_lower:
        return "bell"
    return "sparkles"
